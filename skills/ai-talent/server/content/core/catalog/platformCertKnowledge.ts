import type { FBTaskTemplate } from "./quickTaskFB";

export type CertMission = "facebook";

const CERT_KNOWLEDGE: Record<CertMission, string> = {
  facebook: `
# Facebook 平台知識（依 Meta 認證考試範圍整理——寫之前先對照）
【行動優先的創意（創意策略範圍）】
- 人是用拇指滑過去的：動態牆只露前兩行，其餘收在「查看更多」後面（約 125 個字元之後）。最重要的一句話放最前面，不要用前兩行鋪陳。
- 一則只講一個訊息。想講第二件事，就是下一則。
- 影片與 Reels：前三秒要讓人知道這跟他有什麼關係；多數人關著聲音看，重點要有字卡，不能只靠旁白；直式畫面；品牌或產品在前幾秒就出現，不要留到最後才揭曉。
- 為版位寫，不是一稿通用：動態貼文、限時動態、Reels、直播、廣告，各自的長度與開頭方式不同——照這張任務卡指定的形式寫。
【社群經營（社群經理範圍）】
- 每一則都要有一個明確目的：讓人留言、分享、存起來，或點出去。目的不同，結尾的寫法就不同；不要每一則都以「立即選購」收尾。
- 要人留言，就問一個他答得出來、而且答案值得說的具體問題；「你覺得呢？」不算。
- 回覆留言與處理負評：先回應對方說的那件事，再給下一步；不爭辯、不刪文了事、不用罐頭回覆。涉及個別訂單或個資，請對方私訊。
- 社群守則與辦活動的規矩：抽獎、徵件要把參加方式、期間、名額寫清楚；不能要求「分享到個人動態牆」或「標註朋友」當成參加條件。
【廣告與政策（數位行銷助理／媒體採購範圍）】
- 行動呼籲要對應目的：要認知就邀他看、要互動就邀他回、要轉換才叫他買。一則一個行動呼籲。
- 個人屬性：不能寫得像你知道對方的身體、健康、財務、年齡、感情或信仰狀況。「你是不是也有三高？」「正在為債務煩惱的你」這種句子會被擋。改寫成描述產品或情境，不要描述讀者本人。
- 不能保證成效、不能用誇大或無法證實的比較（「第一」「最便宜」「保證」）；食品與保健類不能寫療效。
- 不用前後對比圖、不拿身體部位的缺陷當賣點、不用聳動或羞辱人的說法。
- 廣告文字：主文重點放在前兩行；標題短到一眼看完；說明欄補標題沒講的具體資訊，不要重複標題。
`.trim(),
};

/** 這張卡屬於哪個已經整理好認證知識的 mission；還沒整理到的平台回 null（行為完全不變）。 */
export function certMissionOf(template: Pick<FBTaskTemplate, "id"> & { outputDefaults?: { platform?: string } | null }): CertMission | null {
  const id = String(template.id ?? "");
  if (/^fb-/.test(id)) return "facebook";
  return null;
}

export function certKnowledgeBlock(mission: CertMission | null): string {
  return mission ? `\n\n${CERT_KNOWLEDGE[mission]}\n` : "";
}

